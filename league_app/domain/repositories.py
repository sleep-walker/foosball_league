# ---------------------------------------------------------------------------
# Tournament
# ---------------------------------------------------------------------------

@runtime_checkable
class ITournamentRepository(Protocol):
    async def get(self, uuid: UUID) -> Tournament | None: ...
    async def list_all(self, include_deleted: bool = False) -> list[Tournament]: ...
    async def list_by_league(self, league_id: UUID) -> list[Tournament]: ...
    async def create(self, tournament: Tournament) -> Tournament: ...
    async def update(self, tournament: Tournament) -> Tournament: ...
    async def delete(self, uuid: UUID) -> None: ...

    # Registration
    async def get_registration(
        self, tournament_id: UUID, player_id: UUID
    ) -> TournamentRegistration | None: ...
    async def list_registrations(
        self, tournament_id: UUID
    ) -> list[TournamentRegistration]: ...
    async def add_registration(self, reg: TournamentRegistration) -> TournamentRegistration: ...
    async def update_registration(self, reg: TournamentRegistration) -> TournamentRegistration: ...
    async def remove_registration(self, tournament_id: UUID, player_id: UUID) -> bool: ...

    # Applicants
    async def list_applicants(self, tournament_id: UUID) -> list[Player]: ...
    async def add_applicant(self, tournament_id: UUID, player_id: UUID) -> None: ...
    async def remove_applicant(self, tournament_id: UUID, player_id: UUID) -> None: ...


