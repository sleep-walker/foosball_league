"""Abstract repository interfaces (ports).

Services depend on these protocols — never on a concrete DB implementation.
The infrastructure layer provides concrete adapters (SQLAlchemy, in-memory, …).
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable
from uuid import UUID

from .entities import (
    Game,
    Match,
    Player,
    Stage,
    Team,
    Tournament,
    TournamentRegistration,
    GameTable,
)
from .entities_league import League


# ---------------------------------------------------------------------------
# Player
# ---------------------------------------------------------------------------

@runtime_checkable
class IPlayerRepository(Protocol):
    async def get(self, uuid: UUID) -> Player | None: ...
    async def get_by_user_id(self, user_id: UUID) -> Player | None: ...
    async def list_all(self) -> list[Player]: ...
    async def create(self, player: Player) -> Player: ...
    async def update(self, player: Player) -> Player: ...
    async def delete(self, uuid: UUID) -> None: ...


# ---------------------------------------------------------------------------
# Team
# ---------------------------------------------------------------------------

@runtime_checkable
class ITeamRepository(Protocol):
    async def get(self, uuid: UUID) -> Team | None: ...
    async def list_by_tournament(self, tournament_id: UUID) -> list[Team]: ...
    async def create(self, team: Team) -> Team: ...


# ---------------------------------------------------------------------------
# Match & Game
# ---------------------------------------------------------------------------

@runtime_checkable
class IMatchRepository(Protocol):
    async def get(self, uuid: UUID) -> Match | None: ...
    async def list_by_tournament(self, tournament_id: UUID) -> list[Match]: ...
    async def list_by_stage(self, stage_id: UUID) -> list[Match]: ...
    async def create(self, match: Match) -> Match: ...
    async def update(self, match: Match) -> Match: ...
    async def delete(self, uuid: UUID) -> None: ...

    # Game sub-entity
    async def get_game(self, uuid: UUID) -> Game | None: ...
    async def list_games(self, match_id: UUID) -> list[Game]: ...
    async def create_game(self, game: Game) -> Game: ...
    async def update_game(self, game: Game) -> Game: ...


